const LOCKFILE = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4
`;

const HOST_SOURCE = `fn main() {
    if std::env::args().nth(1).as_deref() == Some("--export-native") {
        println!("export const answer=42;");
    }
}
`;

async function fixture(
  prefix: string,
  options: { readonly lockfile?: boolean; readonly buildScript?: boolean } = {},
): Promise<string> {
  const directory = await realpath(await mkdtemp(join(tmpdir(), prefix)));
  await mkdir(join(directory, "src"), { recursive: true });
  await writeFile(
    join(directory, "Cargo.toml"),
    `[package]
name = "native-project-fixture"
version = "0.0.0"
edition = "2024"${options.buildScript ? '\nbuild = "build.rs"' : ""}

[workspace]

[[bin]]
name = "native-project-host"
path = "src/main.rs"
`,
  );
  await writeFile(join(directory, "src/main.rs"), HOST_SOURCE);
  if (options.lockfile !== false) {
    await writeFile(
      join(directory, "Cargo.lock"),
      `${LOCKFILE}
[[package]]
name = "native-project-fixture"
version = "0.0.0"
`,
    );
  }
  await writeFile(join(directory, "package.json"), '{"type":"module"}');
  await writeFile(join(directory, "app.js"), 'import { answer } from "#native";\nconsole.log(answer);\n');
  return directory;
}

function configSource(options: string): string {
  return `import { solidGpui } from ${JSON.stringify(plugin)};
export default { root: import.meta.dirname, plugins: [solidGpui(${options})] };
`;
}

test("prepare publishes bindings, the prepared tsconfig and the artifact record without building the app", async () => {
  const directory = await fixture("solid-project-prepare-");
  const bindings = join(directory, ".generated/native.ts");
  const tsconfig = join(directory, ".solid-gpui/tsconfig.json");
  try {
    await writeFile(
      join(directory, "vite.config.ts"),
      configSource(`{ entry: "app.js", native: { manifestPath: "Cargo.toml", bin: "native-project-host" } }`),
    );
    const prepared = await prepareProject({ root: directory });
    expect(await readFile(bindings, "utf8")).toBe("export const answer = 42;\n");
    // The generated config must map the same specifiers the runtime aliases resolve, and stand on
    // its own: a consumer extends it with only their own strictness and include.
    expect(JSON.parse(await readFile(tsconfig, "utf8"))).toEqual({
      compilerOptions: {
        target: "ES2024",
        module: "preserve",
        moduleResolution: "bundler",
        jsx: "preserve",
        jsxImportSource: "@solid-gpui/core",
        noEmit: true,
        allowImportingTsExtensions: true,
        paths: {
          "#native": [bindings],
          "@solid-gpui/core/components": [bindings],
        },
      },
    });
    expect(prepared.project.aliases).toEqual([
      { find: "#native", replacement: bindings },
      { find: "@solid-gpui/core/components", replacement: bindings },
    ]);
    // Preparing never produces the application bundle.
    await expect(stat(join(directory, "dist"))).rejects.toThrow();

    const artifacts = await readNativeArtifacts(directory);
    expect(artifacts?.native?.profileDirectory).toBe("debug");
    expect(artifacts?.native?.locked).toBe(true);
    expect(artifacts?.native?.bin).toBe("native-project-host");
    expect(artifacts?.bundle).toBe(join(directory, "dist/app.js"));
    // The record's derived expectation must agree with the executable Cargo actually produced.
    expect(expectedExecutablePath(artifacts!)).toBe(artifacts?.native?.executable);
    expect(recordedHostExecutable(artifacts!)).toBe(artifacts?.native?.executable);
    expect(await stat(recordedHostExecutable(artifacts!)!)).toBeTruthy();

    // A production build publishes the same record, now with the bundle it really emitted.
    const { build } = await import("vite");
    await build({ configFile: join(directory, "vite.config.ts"), root: directory, logLevel: "silent" });
    expect(await stat(join(directory, "dist/app.js"))).toBeTruthy();
    const built = await readNativeArtifacts(directory);
    expect(built?.bundle).toBe(join(directory, "dist/app.js"));
    expect(built?.host?.command).toBe(built?.native?.executable);

    await checkProject({ root: directory });
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}, 60000);

