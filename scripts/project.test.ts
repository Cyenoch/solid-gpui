test("preview runs the recorded host against the production bundle, or explains what is missing", async () => {
  const directory = await fixture("solid-project-preview-");
  const observation = join(directory, "observation.json");
  const runtime = join(directory, "runtime.js");
  try {
    await writeFile(
      join(directory, "vite.config.ts"),
      configSource(
        `{ entry: "app.js", runtime: "quickjs", native: { manifestPath: "Cargo.toml", bin: "native-project-host" } }`,
      ),
    );
    await writeFile(
      runtime,
      `await Bun.write(${JSON.stringify(observation)}, JSON.stringify({ args: Bun.argv.slice(2), runner: process.env.SOLID_GPUI_VITE_RUNNER ?? null }));\nprocess.exit(7);\n`,
    );
    // Nothing is built yet: preview must name the command that produces the bundle.
    await expect(previewApplication({ root: directory })).rejects.toThrow(/vite build/);

    await mkdir(join(directory, "dist"), { recursive: true });
    await mkdir(join(directory, ".solid-gpui"), { recursive: true });
    await writeFile(join(directory, "dist/app.js"), "// production bundle\n");
    await writeFile(
      join(directory, ".solid-gpui/artifacts.json"),
      serializeNativeArtifacts({
        version: 1,
        root: directory,
        runtime: "quickjs",
        entry: join(directory, "app.js"),
        outDir: join(directory, "dist"),
        tsconfig: join(directory, ".solid-gpui/tsconfig.json"),
        bundle: join(directory, "dist/app.js"),
        host: { command: process.execPath, args: [runtime], output: join(directory, ".generated/native.ts") },
      }),
    );
    // A record for another configuration must not launch an old entry in silence.
    const recorded = await readNativeArtifacts(directory);
    if (!recorded) throw new Error("the fixture should have written an artifact record");
    await writeFile(
      join(directory, ".solid-gpui/artifacts.json"),
      serializeNativeArtifacts({ ...recorded, entry: join(directory, "other-entry.js") }),
    );
    await expect(previewApplication({ root: directory })).rejects.toThrow(/do not match/);

    process.env.SOLID_GPUI_VITE_RUNNER = JSON.stringify(["inherited"]);
    await writeFile(join(directory, ".solid-gpui/artifacts.json"), serializeNativeArtifacts(recorded));
    expect(await previewApplication({ root: directory, args: ["--window", "main"] })).toBe(7);
    delete process.env.SOLID_GPUI_VITE_RUNNER;
    // A QuickJS host must not inherit an enclosing session's Bun runner.
    expect(JSON.parse(await readFile(observation, "utf8"))).toEqual({
      args: ["--runtime", "quickjs", join(directory, "dist/app.js"), "--window", "main"],
      runner: null,
    });
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}, 30000);

